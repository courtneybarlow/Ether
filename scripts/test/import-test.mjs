import { createRequire } from 'node:module';
import { start } from './server.mjs';
const { chromium } = createRequire(import.meta.url)('playwright');
const srv = await start(5181);
const b = await chromium.launch(); const p = await b.newPage({ viewport: { width: 1180, height: 820 } });
const errs = []; p.on('pageerror', e => errs.push(e.message));
await p.addInitScript(() => { window.__SEED = []; });
await p.goto('http://localhost:5181/');
await p.fill('#ether-login input[name=email]', 'c@x.com'); await p.fill('#ether-login input[name=password]', 'pw'); await p.click('#ether-login button');
await p.waitForTimeout(1500);
await p.evaluate(() => window.etherHooks.openDrawer('voice'));
await p.setInputFiles('#import-file', process.env.EXPORT);
await p.waitForFunction(() => /Imported/.test(document.getElementById('import-state').textContent), null, { timeout: 30000 });
console.log(await p.textContent('#import-state'));
const r = await p.evaluate(() => ({ n: window.__rows.size, priv: [...window.__rows.keys()].filter(k => k.startsWith('data/')), items: [...window.__rows.keys()].filter(k => k.startsWith('items/')).length }));
await p.waitForTimeout(1500);
await p.keyboard.press('Escape'); await p.waitForTimeout(500);
r.meta = await p.textContent('#today-meta');
await p.screenshot({ path: process.env.OUT + '/after-import.png' });
console.log(JSON.stringify(r), errs);
await b.close(); srv.close();
